export const GLOBAL_SUPPORTED_LANGUAGE_TAGS: readonly string[] = Object.freeze(
  GLOBAL_LANGUAGE_CATALOG.map(l => l.tag)
);

/**
 * Retrieves locale metadata by BCP-47 tag.
 */
export function getLanguageDefinition(tag: string): GlobalLocaleDefinition | null {
  if (!tag || typeof tag !== 'string') return null;
  const normalized = tag.trim();
  return GLOBAL_LANGUAGE_CATALOG.find(l => l.tag === normalized) ?? null;
}

/**
 * Checks if a language tag is supported in the global catalog.
 */
export function isSupportedLanguageTag(tag: string): boolean {
  if (!tag || typeof tag !== 'string') return false;
  return GLOBAL_SUPPORTED_LANGUAGE_TAGS.includes(tag.trim());
}

/**
 * Strict Production Selectability Gate:
 * Only languages with releaseStatus === 'PRODUCTION_READY' are selectable in production.
 */
export function isLanguageProductionSelectable(tag: string): boolean {
  const def = getLanguageDefinition(tag);
  if (!def) return false;
  return def.enabled === true && def.releaseStatus === 'PRODUCTION_READY';
}
