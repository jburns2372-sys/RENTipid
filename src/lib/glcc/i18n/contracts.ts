export type GlccCanonicalTranslationKey = (typeof GLCC_CANONICAL_KEYS)[number];

export interface TranslationBundle {
  readonly locale: string; // Canonical BCP 47 tag, e.g. 'en-PH'
  readonly direction: 'ltr' | 'rtl';
  readonly version: string;
  readonly isFixture?: boolean;
  readonly messages: Record<GlccCanonicalTranslationKey, string>;
}

export interface TranslationParams {
  [key: string]: string | number;
}

export interface TranslationEngineOptions {
  readonly defaultLocale?: string;
  readonly onMissingKey?: (key: string, locale: string) => void;
  readonly onFallbackUsed?: (key: string, requestedLocale: string, fallbackLocale: string) => void;
}

export interface CurrencyFormatOptions {
  readonly display?: 'symbol' | 'narrowSymbol' | 'code' | 'name';
  readonly minorUnitExponent?: number; // Override/enforce exponent (e.g. 0 for JPY, 2 for PHP/USD, 3 for BHD)
}

export interface PluralForms {
  readonly one: string;
  readonly other: string;
  readonly zero?: string;
  readonly two?: string;
  readonly few?: string;
  readonly many?: string;
}

export interface BundleValidationResult {
  readonly isValid: boolean;
  readonly locale: string;
  readonly missingKeys: string[];
  readonly extraKeys: string[];
  readonly placeholderMismatches: Array<{
    key: string;
    expected: string[];
    actual: string[];
  }>;
}
